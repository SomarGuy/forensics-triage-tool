def jpeg_bytes(label: str, exif_thumbnail: bool = False) -> bytes:
    com = f"SYNTHETIC {label}".encode()
    out = BASE_JPEG[:2] + b"\xff\xfe" + struct.pack(">H", len(com) + 2) + com
    if exif_thumbnail:
        payload = b"Exif\x00\x00" + BASE_JPEG          # the thumbnail has its own SOI and EOI
        out += b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload
    return out + BASE_JPEG[2:]


def _chunk(t: bytes, d: bytes) -> bytes:
    return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)


def png_bytes(label: str, w: int = 24, h: int = 16, shade: int = 90) -> bytes:
    raw = b"".join(b"\x00" + b"".join(bytes(((shade + x * 3) % 256, (shade + y * 5) % 256, 160)) for x in range(w)) for y in range(h))
    text = f"Comment\x00SYNTHETIC {label}".encode()
    return (b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + _chunk(b"tEXt", text)
            + _chunk(b"IDAT", zlib.compress(raw, 0)) + _chunk(b"IEND", b""))


def zip_bytes(members: Dict[str, bytes], date=(2026, 1, 1, 0, 0, 0)) -> bytes:
    buf = BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as zf:
        for name, data in members.items():
            zi = zipfile.ZipInfo(name, date)
            zi.compress_type = zipfile.ZIP_STORED
            zi.create_system = 3
            zi.external_attr = 0o600 << 16
            zf.writestr(zi, data)
    return buf.getvalue()


