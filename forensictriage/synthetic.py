# ------------------------------------------------------------------ SQLite (Chrome-like History)
HISTORY_SCHEMA = [
    "CREATE TABLE urls(id INTEGER PRIMARY KEY AUTOINCREMENT, url LONGVARCHAR, title LONGVARCHAR, visit_count INTEGER DEFAULT 0 NOT NULL, typed_count INTEGER DEFAULT 0 NOT NULL, last_visit_time INTEGER NOT NULL, hidden INTEGER DEFAULT 0 NOT NULL)",
    "CREATE TABLE visits(id INTEGER PRIMARY KEY, url INTEGER NOT NULL, visit_time INTEGER NOT NULL, from_visit INTEGER, transition INTEGER DEFAULT 0 NOT NULL, segment_id INTEGER, visit_duration INTEGER DEFAULT 0 NOT NULL)",
    "CREATE TABLE downloads(id INTEGER PRIMARY KEY, guid VARCHAR NOT NULL, current_path LONGVARCHAR NOT NULL, target_path LONGVARCHAR NOT NULL, start_time INTEGER NOT NULL, received_bytes INTEGER NOT NULL, total_bytes INTEGER NOT NULL, state INTEGER NOT NULL, danger_type INTEGER NOT NULL, interrupt_reason INTEGER NOT NULL, end_time INTEGER NOT NULL, opened INTEGER NOT NULL, referrer VARCHAR NOT NULL, tab_url VARCHAR NOT NULL, mime_type VARCHAR(255) NOT NULL)",
    "CREATE TABLE keyword_search_terms(keyword_id INTEGER NOT NULL, url_id INTEGER NOT NULL, term LONGVARCHAR NOT NULL, normalized_term LONGVARCHAR NOT NULL)",
]


def build_history(path: Path, visits: List[tuple], searches: List[tuple], downloads: List[tuple]) -> None:
    """visits: (time_ns, url, title, transition); searches: (time_ns, term, url); downloads: (start_ns, end_ns, target, size, tab_url, mime)."""
    if path.exists():
        path.unlink()
    con = sqlite3.connect(path)
    con.execute("PRAGMA page_size=4096")
    con.execute("PRAGMA journal_mode=DELETE")
    for stmt in HISTORY_SCHEMA:
        con.execute(stmt)
    url_ids: Dict[str, int] = {}

    def url_id(url: str, title: str, t: int, typed: bool) -> int:
        if url not in url_ids:
            cur = con.execute("INSERT INTO urls(url,title,visit_count,typed_count,last_visit_time) VALUES(?,?,?,?,?)", (url, title, 0, 0, ns_to_webkit(t)))
            url_ids[url] = cur.lastrowid
        uid = url_ids[url]
        con.execute("UPDATE urls SET visit_count=visit_count+1, typed_count=typed_count+?, last_visit_time=MAX(last_visit_time, ?) WHERE id=?", (1 if typed else 0, ns_to_webkit(t), uid))
        return uid
    for t, url, title, trans in sorted(visits):
        uid = url_id(url, title, t, trans == 1)
        con.execute("INSERT INTO visits(url,visit_time,from_visit,transition,visit_duration) VALUES(?,?,?,?,?)", (uid, ns_to_webkit(t), 0, trans, 12_000_000))
    for t, term, url in sorted(searches):
        uid = url_id(url, f"{term} - Search", t, False)
        con.execute("INSERT INTO visits(url,visit_time,from_visit,transition,visit_duration) VALUES(?,?,?,?,?)", (uid, ns_to_webkit(t), 0, 0, 3_000_000))
        con.execute("INSERT INTO keyword_search_terms VALUES(?,?,?,?)", (2, uid, term, term.lower()))
    for i, (st, et, target, size, tab, mime) in enumerate(downloads, 1):
        con.execute("INSERT INTO downloads VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (i, f"00000000-0000-4000-8000-{i:012d}", target, target, ns_to_webkit(st), size, size, 1, 0, 0, ns_to_webkit(et), 1, tab, tab, mime))
    con.commit()
    con.close()
    data = bytearray(path.read_bytes())
    data[92:96] = data[24:28]                       # version-valid-for = file change counter
    data[96:100] = struct.pack(">I", 3045000)       # pin the writer's SQLite version number
    path.write_bytes(bytes(data))


# ------------------------------------------------------------------ time helpers
def T(s: str) -> int:
    v = parse_ts(s)
    assert v is not None, s
    return v


class Clock:
    """Random 100 ns fractions so benign timestamps are never accidentally 'whole seconds'."""
    def __init__(self, rng: random.Random):
        self.rng = rng

    def frac(self, s: str) -> int:
        return T(s) + self.rng.randrange(1, 10_000_000) * 100


# ------------------------------------------------------------------ the case
def _filler(rng: random.Random, sectors: int, kind: str = "random") -> bytes:
    if kind == "zero":
        return b"\x00" * (512 * sectors)
    out = bytearray()
    for _ in range(sectors):
        r = rng.random()
        if r < 0.25:
            out += b"\x00" * 512
        elif r < 0.35:
            out += (b"sector remnant; fictional text; no indicators here. " * 12)[:512]
        else:
            blob = bytearray(rng.randbytes(512))
            # keep accidental file signatures out of the filler so the planted ones are the only ones
            for sig in (b"\xff\xd8\xff", b"\x89PNG", b"%PDF", b"PK\x03", b"PK\x05"):
                while sig in blob:
                    i = blob.find(sig)
                    blob[i] ^= 0x5A
            out += bytes(blob)
    return bytes(out)


def _pad(b: bytes) -> bytes:
    return b + b"\x00" * (-len(b) % 512)


