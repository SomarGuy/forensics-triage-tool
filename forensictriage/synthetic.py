def pdf_bytes(title: str, lines: List[str], created: str, modified: str, jpeg: bytes = b"") -> bytes:
    """A small but valid PDF (correct xref offsets). Text lines must not contain backslashes or parentheses."""
    content = "BT /F1 12 Tf 50 750 Td 14 TL\n" + "\n".join(f"({ln}) Tj T*" for ln in lines) + "\nET"
    if jpeg:
        content += "\nq 64 0 0 64 50 600 cm /Im0 Do Q"
    objs: List[bytes] = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >>"
        + (b" /XObject << /Im0 6 0 R >>" if jpeg else b"") + b" >> >>",
        b"<< /Length %d >>\nstream\n" % len(content) + content.encode() + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    if jpeg:
        objs.append(b"<< /Type /XObject /Subtype /Image /Width 16 /Height 16 /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length %d >>\nstream\n" % len(jpeg) + jpeg + b"\nendstream")
    objs.append(f"<< /Title ({title}) /Producer (forensictriage synthetic generator) /CreationDate (D:{created}Z) /ModDate (D:{modified}Z) >>".encode())
    out = BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, 1):
        offsets.append(out.tell())
        out.write(b"%d 0 obj\n" % i + body + b"\nendobj\n")
    xref = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1))
    for o in offsets:
        out.write(b"%010d 00000 n \n" % o)
    out.write(b"trailer\n<< /Size %d /Root 1 0 R /Info %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, len(objs), xref))
    return out.getvalue()


