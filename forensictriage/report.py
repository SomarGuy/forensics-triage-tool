"""JSON and Markdown case reports, plus the output writer."""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Dict, List

from . import __version__, TOOL_NAME
from .config import SEVERITIES
from .custody import verify_chain
from .timestomp import YEAR_1980_NS
from .timeutil import format_ts, to_ms, NS

SYNTHETIC_NOTICE = ("SYNTHETIC DATA. Every file, timestamp, browser entry, registry value and raw image in this case was generated by "
                    "a script (forensictriage/synthetic.py). The people, company, devices and domains are fictional; web addresses use "
                    "reserved or fictional names and IP addresses come from RFC 5737 documentation ranges.")
REAL_NOTICE = "Report produced from the evidence supplied to the tool. Review every finding before relying on it."
DAY_NS = 86400 * NS


def _window(findings) -> dict:
    times = [f.first_seen for f in findings if f.severity in ("critical", "high", "medium") and f.first_seen and f.first_seen > YEAR_1980_NS]
    times += [f.last_seen for f in findings if f.severity in ("critical", "high", "medium") and f.last_seen and f.last_seen > YEAR_1980_NS]
    if not times:
        return {}
    lo = (min(times) // DAY_NS) * DAY_NS
    hi = (max(times) // DAY_NS + 1) * DAY_NS
    return {"start_ms": to_ms(lo), "end_ms": to_ms(hi), "start": format_ts(lo, 0), "end": format_ts(hi, 0)}


def build_report(res) -> dict:
    a, inp = res.analysis, res.inputs
    cfg = a.cfg
    sev = Counter(f.severity for f in res.findings)
    flagged = [f for f in a.files if any(x in f.flags for x in ("known_bad", "signature_mismatch", "timestomp_likely", "timestamp_weak", "staging_dir", "recycle_bin"))]
    techniques: Dict[str, dict] = {}
    for f in res.findings:
        for m in f.mitre:
            t = techniques.setdefault(m["id"], {"id": m["id"], "name": m["name"], "findings": []})
            t["findings"].append(f.id)
    ext_iocs = [i for i in a.iocs if i.scope == "external" or i.known_bad]
    ok_chain, _bad, chain_reason = verify_chain(res.custody.entries)
    visits_all = []
    for b in a.browsers:
        visits_all += b.visits
    narrative = sorted(
        ({"time": format_ts(f.first_seen, 0), "ms": to_ms(f.first_seen), "finding": f.id, "severity": f.severity, "title": f.title}
         for f in res.findings if f.first_seen and f.first_seen > YEAR_1980_NS),
        key=lambda x: (x["ms"], x["finding"]))
    return {
        "meta": {
            "tool": TOOL_NAME, "version": __version__, "generated_at": format_ts(res.finished_ns, 0) + " UTC",
            "synthetic": inp.synthetic, "case_id": inp.case_id, "title": inp.title, "examiner": inp.examiner,
            "description": inp.description, "evidence_acquired_at": format_ts(inp.acquired_at, 0) + " UTC" if inp.acquired_at else "",
            "notice": SYNTHETIC_NOTICE if inp.synthetic else REAL_NOTICE,
            "evidence_root": inp.root.name, "raw_images": [Path(p).name for p in inp.raw_images],
        },
        "summary": {
            "files": len(a.files), "bytes": sum(f.size for f in a.files), "findings": len(res.findings), "by_severity": {s: sev.get(s, 0) for s in SEVERITIES},
            "flagged_files": len(flagged), "known_bad": sum(1 for f in a.files if f.hash_status == "known_bad"),
            "known_good": sum(1 for f in a.files if f.hash_status == "known_good"),
            "signature_mismatches": sum(1 for f in a.files if "signature_mismatch" in f.flags),
            "timestomp_likely": sum(1 for f in a.files if "timestomp_likely" in f.flags),
            "timestamp_weak": sum(1 for f in a.files if "timestamp_weak" in f.flags),
            "iocs": len(a.iocs), "iocs_external": len(ext_iocs),
            "carved_complete": sum(1 for c in a.carved if c["status"] == "complete"), "carved_partial": sum(1 for c in a.carved if c["status"] == "partial"),
            "recycle_records": len(a.recycle), "mft_deleted": len(a.mft_deleted), "timeline_events": len(res.timeline),
            "usb_devices": len(a.usb), "browser_visits": len(visits_all), "prefetch_entries": len(a.prefetch),
            "techniques": len(techniques), "integrity_ok": res.integrity_ok,
        },
        "integrity": {
            "ok": res.integrity_ok, "differences": res.differences,
            "before": {"files": len(res.before.entries), "bytes": res.before.total_bytes, "manifest_sha256": res.before.digest()},
            "after": {"files": len(res.after.entries), "bytes": res.after.total_bytes, "manifest_sha256": res.after.digest()},
            "skipped": res.before.skipped,
            "custody_chain_ok": ok_chain, "custody_chain_note": chain_reason, "custody": res.custody.to_list(),
            "method": ("All evidence is opened read-only (O_RDONLY, SQLite mode=ro&immutable=1). Every file is hashed (MD5, SHA-1, SHA-256) and stat-ed before analysis "
                       "and again after; any change in content, size, mtime or mode is reported. Outputs are written outside the evidence folders. "
                       "Access times are not compared because reading can legitimately change them on some file systems."),
        },
        "window": _window(res.findings),
        "findings": [f.to_dict() for f in res.findings],
        "narrative": narrative,
        "files": [f.to_dict() for f in a.files],
        "timeline": [e.to_dict() for e in res.timeline],
        "iocs": [i.to_dict() for i in a.iocs],
        "carved": {"files": a.carved, "stats": a.carve_stats},
        "deleted": {
            "recycle_bin": [dict(r, deleted=format_ts(r.get("deleted_ns"), 0)) for r in a.recycle],
            "mft_entries": [dict(m, when=format_ts(m.get("when_ns"), 0)) for m in a.mft_deleted],
        },
        "browser": {
            "sources": [{"path": b.path, "urls": b.urls, "visits": len(b.visits), "downloads": len(b.downloads), "searches": len(b.searches)} for b in a.browsers],
            "flagged_visits": [{"time": format_ts(v["time_ns"], 0), "category": v["category"], "url": v["url"], "title": v["title"]} for v in a.visit_hits],
            "flagged_searches": [{"time": format_ts(s["time_ns"], 0), "category": s["category"], "term": s["term"]} for s in a.search_hits],
            "downloads": [{"time": format_ts(d["start_ns"], 0), "target_path": d["target_path"], "from": d["tab_url"], "bytes": d["bytes"], "mime": d["mime_type"]} for b in a.browsers for d in b.downloads],
        },
        "artifacts": {
            "prefetch": [{"executable": p.executable, "run_count": p.run_count, "last_runs": [format_ts(t, 0) for t in p.last_runs_ns], "path": p.path} for p in a.prefetch],
            "usb_devices": [{"vendor": d.vendor, "product": d.product, "serial": d.serial, "friendly_name": d.friendly_name, "drive_letter": d.drive_letter,
                             "first_install": format_ts(d.first_install_ns, 0), "last_arrival": format_ts(d.last_arrival_ns, 0), "last_removal": format_ts(d.last_removal_ns, 0)} for d in a.usb],
            "recent_docs": [{"name": v.value_name, "target": v.value_data, "time": format_ts(v.last_write_ns, 0)} for v in a.recent_docs],
            "registry_values": len(a.registry),
        },
        "mitre": sorted(techniques.values(), key=lambda t: t["id"]),
        "rules": [{"id": r["id"], "title": r["title"], "severity": r["severity"], "category": r["category"], "mitre": r["mitre"]} for r in cfg["rules"]],
        "notes": a.notes,
    }


def md(s) -> str:
    """Make arbitrary evidence text safe for a Markdown table or list item (no backticks, pipes or line breaks)."""
    return str(s).replace("`", "'").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def render_markdown(rep: dict) -> str:
    m, s, ig = rep["meta"], rep["summary"], rep["integrity"]
    L: List[str] = []
    L.append(f"# Forensic triage report: {md(m['case_id'])}")
    L.append("")
    L.append(f"> **{md(m['notice'])}**")
    L.append("")
    L.append(f"**{md(m['title'])}**" if m["title"] else "")
    L.append("")
    L.append("| | |\n|---|---|")
    L.append(f"| Examiner | {md(m['examiner'] or 'unspecified')} |")
    L.append(f"| Generated | {m['generated_at']} by {m['tool']} {m['version']} |")
    if m["evidence_acquired_at"]:
        L.append(f"| Evidence acquired | {m['evidence_acquired_at']} |")
    L.append(f"| Evidence | folder `{md(m['evidence_root'])}`" + (f", raw image(s) {', '.join('`' + md(x) + '`' for x in m['raw_images'])}" if m["raw_images"] else "") + " |")
    L.append(f"| Files analysed | {s['files']} ({s['bytes']:,} bytes) |")
    L.append(f"| Findings | {s['findings']}: " + ", ".join(f"{s['by_severity'][k]} {k}" for k in SEVERITIES) + " |")
    L.append(f"| Evidence integrity | **{'VERIFIED UNCHANGED' if ig['ok'] else 'CHANGED DURING ANALYSIS'}** |")
    L.append("")
    if m["description"]:
        L.append(md(m["description"]))
        L.append("")
    L.append("## Evidence integrity and chain of custody")
    L.append("")
    L.append(md(ig["method"]))
    L.append("")
    L.append(f"- Before: {ig['before']['files']} files, {ig['before']['bytes']:,} bytes, manifest SHA-256 `{ig['before']['manifest_sha256']}`")
    L.append(f"- After:  {ig['after']['files']} files, {ig['after']['bytes']:,} bytes, manifest SHA-256 `{ig['after']['manifest_sha256']}`")
    L.append(f"- Result: **{'identical' if ig['ok'] else str(len(ig['differences'])) + ' difference(s)'}**; custody chain: {md(ig['custody_chain_note'])}")
    for d in ig["differences"]:
        L.append(f"  - {md(d['label'])}: {d['change']} ({md(d['detail'])})")
    L.append("")
    L.append("| # | Time (UTC) | Action | Detail |\n|---|---|---|---|")
    for e in ig["custody"]:
        L.append(f"| {e['seq']} | {e['time']} | {e['action']} | {md(e['detail'])} |")
    L.append("")
    L.append("## Findings")
    L.append("")
    if not rep["findings"]:
        L.append("No findings.")
    for f in rep["findings"]:
        L.append(f"### {f['id']} [{f['severity'].upper()}] {md(f['title'])}")
        L.append("")
        L.append(f"Rule {f['rule']} · {md(f['category'])}" + (f" · first seen {f['first_seen']} UTC" if f["first_seen"] else "")
                 + (" · ATT&CK: " + ", ".join(f"{t['id']} {md(t['name'])}" for t in f["mitre"]) if f["mitre"] else ""))
        L.append("")
        L.append(md(f["summary"]))
        L.append("")
        for e in f["evidence"]:
            L.append(f"- {md(e)}")
        if f["files"]:
            L.append(f"- Files: " + ", ".join(f"`{md(x)}`" for x in f["files"][:12]) + (" …" if len(f["files"]) > 12 else ""))
        L.append("")
        L.append("Recommended response:")
        for i, r in enumerate(f["response"], 1):
            L.append(f"{i}. {md(r)}")
        L.append("")
    L.append("## Case timeline (key events from findings)")
    L.append("")
    L.append("| Time (UTC) | Finding | Severity | Event |\n|---|---|---|---|")
    for n in rep["narrative"]:
        L.append(f"| {n['time']} | {n['finding']} | {n['severity']} | {md(n['title'])} |")
    L.append("")
    L.append("## Flagged files")
    L.append("")
    L.append("| File | Size | Detected as | Flags | SHA-256 |\n|---|---|---|---|---|")
    for f in rep["files"]:
        if any(x in f["flags"] for x in ("known_bad", "signature_mismatch", "timestomp_likely", "timestamp_weak", "staging_dir")):
            L.append(f"| {md(f['path'])} | {f['size']:,} | {md(f['detected'])} | {', '.join(f['flags'])} | `{f['sha256'][:16]}…` |")
    L.append("")
    L.append("## Carved files (recovered from raw image)")
    L.append("")
    st = rep["carved"]["stats"]
    for x in st:
        L.append(f"- {md(x['image'])}: {x['bytes_scanned']:,} bytes scanned, {x['headers_found']} headers, {x['complete']} complete, {x['partial']} partial, {x['rejected']} rejected as false positives, {x['nested_skipped']} nested headers skipped")
    L.append("")
    L.append("| ID | Type | Offset | Length | Status | Matches | SHA-256 |\n|---|---|---|---|---|---|---|")
    for c in rep["carved"]["files"]:
        match = c["matches_file"] or c["matches_recycle"] or c["matches_mft"] or ""
        L.append(f"| {c['id']} | {c['kind']} | 0x{c['offset']:x} | {c['length']:,} | {c['status']} | {md(match)} | `{c['sha256'][:16]}…` |")
    L.append("")
    L.append("## External indicators")
    L.append("")
    L.append("| Type | Value | Scope | Count | Found in |\n|---|---|---|---|---|")
    for i in rep["iocs"]:
        if i["scope"] == "external" or i.get("known_bad"):
            L.append(f"| {i['type']} | {md(i['value'])} | {i['scope'] or ('KNOWN-BAD: ' + md(i.get('known_bad', '')))} | {i['count']} | {md(', '.join(i['sources'][:3]))} |")
    L.append("")
    L.append("## Method notes and limits")
    L.append("")
    L.append("Findings are rule-based leads for a human examiner, not conclusions. Timestamp indicators are weighted because copies, FAT volumes and archive tools produce harmless oddities. "
             "Carving recovers content, not names or dates. Prefetch, registry and MFT inputs are parsed from exports, not from raw binary structures.")
    if rep["notes"]:
        L.append("")
        L.append("Processing notes:")
        for n in rep["notes"]:
            L.append(f"- {md(n)}")
    return "\n".join(L) + "\n"


def write_json(path, data) -> str:
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    Path(path).write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def write_case_outputs(res) -> None:
    out = res.out_dir
    out.mkdir(parents=True, exist_ok=True)
    rep = build_report(res)
    j_hash = write_json(out / "case_report.json", rep)
    md_text = render_markdown(rep)
    (out / "case_report.md").write_text(md_text, encoding="utf-8")
    m_hash = hashlib.sha256(md_text.encode("utf-8")).hexdigest()
    write_json(out / "evidence_manifest.json", res.before.to_dict())
    res.custody.record("REPORT_WRITTEN", f"{TOOL_NAME} {__version__}", "Case report written (JSON and Markdown); the report quotes this log up to the verification step",
                       case_report_json_sha256=j_hash, case_report_md_sha256=m_hash)
    write_json(out / "custody_log.json", {"case_id": res.inputs.case_id, "chain_ok": res.custody.verify()[0], "entries": res.custody.to_list()})
    res.files_written = ["case_report.json", "case_report.md", "evidence_manifest.json", "custody_log.json"]
